async function fetchText(url) {
  // GitHub's raw host rate-limits bursts; back off and try again.
  for (let attempt = 1; ; attempt++) {
    const response = await fetch(url, { headers: { 'user-agent': 'isa-bench notices' } })
    if (response.ok) return (await response.text()).replace(/\r\n/g, '\n').trimEnd()
    const retryable = response.status === 429 || response.status >= 500
    if (!retryable || attempt === 6) throw new Error(`${url}: ${response.status}`)
    await new Promise((done) => setTimeout(done, 5000 * attempt))
  }
}

const RULE = '='.repeat(78)
const printed = new Map()
const out = [
  'THIRD-PARTY NOTICES',
  '',
  'ISA Bench is copyright (c) 2026 Toby Buckmaster and released under the MIT',
  'License (see LICENSE). The desktop app also carries the third-party software',
  'below, each under its own license, reproduced here in full as fetched from',
  'the version the app pins. Electron and Chromium ship their own notices',
  'beside the app (LICENSE.electron.txt, LICENSES.chromium.html).',
  '',
  'Generated by scripts/notices.mjs.',
  '',
]
out.push('Contents', '')
COMPONENTS.forEach((component, i) => out.push(`  ${i + 1}. ${component.name}`))
out.push('')

try {
for (const [i, component] of COMPONENTS.entries()) {
  out.push(RULE, `${i + 1}. ${component.name}`, RULE, '')
  out.push(`Shipped as: ${component.shipped}`, `License:    ${component.license}`, '')
  for (const url of [component.url, ...(component.also ?? [])]) {
    const text = await fetchText(url)
    const hash = createHash('sha256').update(text).digest('hex')
    out.push(`--- ${url}`, '')
    if (printed.has(hash)) {
      out.push(`(Identical to the text printed under ${printed.get(hash)}.)`, '')
      continue
    }
    printed.set(hash, `${i + 1}. ${component.name}`)
    out.push(text, '')
  }
  console.log(`${component.name}: ok`)
}

const path = join(ROOT, 'THIRD-PARTY-NOTICES.txt')
writeFileSync(path, `${out.join('\n')}\n`)
console.log(`wrote ${path}`)
} catch (error) {
  // Nothing is written unless every text was fetched.
  console.error(error.message)
  process.exitCode = 1
}
