// Assembles THIRD-PARTY-NOTICES.txt: the license of every third-party
// component the desktop app ships, fetched at the exact version it pins.
//
//   node scripts/notices.mjs
//
// The installers carry the in-app compiler (LLVM, llvm-mos and the C
// libraries each target links), and their licenses ask for their text to
// travel with the binaries. electron-builder already ships Electron's and
// Chromium's notices; this covers the rest. It needs the network, so it is
// run when a pinned version changes, and its output is committed.
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

